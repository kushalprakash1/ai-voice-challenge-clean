class AccentCache:
    def __init__(self, root: Path | str = DEFAULT_CACHE_ROOT, *, mode: str = ACCENT_MELO_INDIA, scenario: str | None = None):
        if mode not in {ACCENT_MELO_INDIA, ACCENT_CHATTERBOX_KOREAN_HEAVY}:
            raise ValueError("Accent cache mode must be melo_india or chatterbox_korean_heavy")
        self.root = Path(root)
        self.mode = mode
        self.scenario = scenario
        self.lookup_samples_ms: list[float] = []
        self.audio_load_samples_ms: list[float] = []

    @property
    def directory(self) -> Path:
        return self.root / self.mode

    def paths(self, text: str) -> tuple[str, Path, Path]:
        key = accent_cache_key(text, accent_mode=self.mode)
        return key, self.directory / f"{key}.json", self.directory / f"{key}.wav"

    def lookup(self, text: str, *, load_audio: bool = True) -> AccentCacheLookup:
        started = time.perf_counter_ns()
        key, metadata_path, audio_path = self.paths(text)
        try:
            raw = json.loads(metadata_path.read_text(encoding="utf-8"))
            metadata = AccentCacheMetadata(**raw)
            self._validate_metadata(metadata, text=text, key=key, audio_path=audio_path)
        except (OSError, ValueError, TypeError, json.JSONDecodeError) as error:
            lookup_ms = (time.perf_counter_ns() - started) / 1_000_000
            self.lookup_samples_ms.append(lookup_ms)
            return AccentCacheLookup(False, key, None, None, lookup_ms, 0.0, str(error))

        lookup_ms = (time.perf_counter_ns() - started) / 1_000_000
        self.lookup_samples_ms.append(lookup_ms)
        if not load_audio:
            return AccentCacheLookup(True, key, None, metadata, lookup_ms, 0.0)

        load_started = time.perf_counter_ns()
        try:
            pcm = read_validated_pcm(audio_path, expected=metadata)
        except (OSError, ValueError, wave.Error) as error:
            audio_load_ms = (time.perf_counter_ns() - load_started) / 1_000_000
            self.audio_load_samples_ms.append(audio_load_ms)
            return AccentCacheLookup(False, key, None, metadata, lookup_ms, audio_load_ms, str(error))
        audio_load_ms = (time.perf_counter_ns() - load_started) / 1_000_000
        self.audio_load_samples_ms.append(audio_load_ms)
        return AccentCacheLookup(True, key, pcm, metadata, lookup_ms, audio_load_ms)

    def _validate_metadata(self, metadata: AccentCacheMetadata, *, text: str, key: str, audio_path: Path) -> None:
        expected = {
            "cache_key": key,
            "exact_source_text": text,
            "accent_mode": self.mode,
            "accent_backend": "MeloTTS" if self.mode == ACCENT_MELO_INDIA else "Chatterbox Multilingual",
            "melo_speaker": MELO_SPEAKER if self.mode == ACCENT_MELO_INDIA else KOREAN_REFERENCE,
            "sample_rate": SAMPLE_RATE,
            "channels": CHANNELS,
            "sample_width": SAMPLE_WIDTH,
            "encoding": ENCODING,
            "format_version": CACHE_FORMAT_VERSION,
        }
        for field, value in expected.items():
            if getattr(metadata, field) != value:
                raise ValueError(f"accent metadata mismatch: {field}")
        if Path(metadata.generated_audio_path).name != audio_path.name:
            raise ValueError("accent metadata mismatch: generated_audio_path")

    def coverage(self, phrases: Iterable[str]) -> tuple[int, int, tuple[str, ...]]:
        required = tuple(dict.fromkeys(phrases))
        missing = tuple(text for text in required if not self.lookup(text, load_audio=True).hit)
        return len(required), len(required) - len(missing), missing

    def performance(self) -> dict[str, float]:
        return {
            "lookup_p50_ms": _percentile(self.lookup_samples_ms, 50),
            "lookup_p95_ms": _percentile(self.lookup_samples_ms, 95),
            "audio_load_p50_ms": _percentile(self.audio_load_samples_ms, 50),
            "audio_load_p95_ms": _percentile(self.audio_load_samples_ms, 95),
        }


def read_validated_pcm(path: Path, *, expected: AccentCacheMetadata | None = None) -> bytes:
    with wave.open(str(path), "rb") as wav:
        if wav.getframerate() != SAMPLE_RATE or wav.getnchannels() != CHANNELS or wav.getsampwidth() != SAMPLE_WIDTH:
            raise ValueError("accent WAV is not mono 8 kHz PCM16")
        if wav.getcomptype() != "NONE":
            raise ValueError("accent WAV must be uncompressed PCM")
        frames = wav.readframes(wav.getnframes())
    if len(frames) < SAMPLE_WIDTH * 80:
        raise ValueError("accent WAV is empty or too short")
    if len(frames) % SAMPLE_WIDTH:
        raise ValueError("accent PCM has an incomplete sample")
    samples = struct.unpack(f"<{len(frames) // 2}h", frames)
    peak = max(abs(value) for value in samples)
    if peak == 0:
        raise ValueError("accent WAV contains only silence")
    if sum(abs(value) >= 32767 for value in samples) / len(samples) > 0.001:
        raise ValueError("accent WAV has obvious clipping")
    if expected is not None:
        if len(frames) != expected.pcm_bytes or peak != expected.peak_pcm16:
            raise ValueError("accent WAV does not match metadata")
        duration = len(frames) / (SAMPLE_RATE * SAMPLE_WIDTH)
        if abs(duration - expected.duration_seconds) > 1e-9:
            raise ValueError("accent WAV duration does not match metadata")
    return frames


def metadata_for_wav(*, text: str, wav_path: Path, accent_mode: str = ACCENT_MELO_INDIA) -> AccentCacheMetadata:
    pcm = read_validated_pcm(wav_path)
    samples = struct.unpack(f"<{len(pcm) // 2}h", pcm)
    key = accent_cache_key(text, accent_mode=accent_mode)
    return AccentCacheMetadata(
        cache_key=key, exact_source_text=text, accent_mode=accent_mode,
        accent_backend="MeloTTS" if accent_mode == ACCENT_MELO_INDIA else "Chatterbox Multilingual",
        melo_speaker=MELO_SPEAKER if accent_mode == ACCENT_MELO_INDIA else KOREAN_REFERENCE,
        generated_audio_path=str(wav_path), sample_rate=SAMPLE_RATE,
        channels=CHANNELS, sample_width=SAMPLE_WIDTH, encoding=ENCODING,
        format_version=CACHE_FORMAT_VERSION, pcm_bytes=len(pcm),
        duration_seconds=len(pcm) / (SAMPLE_RATE * SAMPLE_WIDTH),
        peak_pcm16=max(abs(value) for value in samples),
    )


def write_metadata(metadata: AccentCacheMetadata, path: Path) -> None:
    path.write_text(json.dumps(asdict(metadata), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def _percentile(values: list[float], percentile: int) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = (len(ordered) - 1) * percentile / 100
    low = int(index)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (index - low)


def accent_cache_preflight(*, scenario: str, mode: str, cache: AccentCache) -> dict[str, object]:
    inventories = {
        MEDICATION_SCENARIO_ID: medication_refill_phrase_inventory,
        OFFICE_SCENARIO_ID: office_location_insurance_phrase_inventory,
        DOCTOR_SCENARIO_ID: doctor_specialist_phrase_inventory,
        FARTHEST_DATE_SCENARIO_ID: farthest_date_phrase_inventory,
    }
    inventory = inventories.get(scenario)
    if inventory is None:
        raise ValueError(f"No accent phrase inventory is defined for scenario={scenario}")
    required, cached, missing = cache.coverage(inventory())
    coverage = 100.0 * cached / required if required else 100.0
    print("================ ACCENT CACHE PREFLIGHT ================", flush=True)
    print(f"scenario={scenario}", flush=True)
    print(f"accent={mode}", flush=True)
    print(f"required_phrases={required}", flush=True)
    print(f"cached={cached}", flush=True)
    print(f"missing={len(missing)}", flush=True)
    print(f"coverage={coverage:.0f}%", flush=True)
    return {"required": required, "cached": cached, "missing": missing, "coverage": coverage}
