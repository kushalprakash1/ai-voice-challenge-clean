# A genuinely cold standalone worker measured 19.99s to publish its flushed
# ready message on this host.  Give the single background worker three cold
# starts' worth of headroom for load variance; this bound is used only when an
# unexpected cache miss actually needs the worker.
MELO_MEASURED_COLD_START_SECONDS = 20.0
MELO_STARTUP_TIMEOUT_SECONDS = MELO_MEASURED_COLD_START_SECONDS * 3
MELO_RENDER_TIMEOUT_SECONDS = 15.0


def accent_mode_from_environment() -> str:
    value = os.environ.get(ACCENT_ENV, ACCENT_NONE).strip().casefold() or ACCENT_NONE
    if value not in {ACCENT_NONE, ACCENT_MELO_INDIA, ACCENT_CHATTERBOX_KOREAN_HEAVY}:
        raise ValueError(f"{ACCENT_ENV} must be one of: none, melo_india, chatterbox_korean_heavy")
    return value


def accent_cache_key(text: str, *, accent_mode: str = ACCENT_MELO_INDIA) -> str:
    if not isinstance(text, str) or not text:
        raise ValueError("Accent cache identity requires non-empty exact text")
    identity = {
        "accent_mode": accent_mode,
        "format_version": CACHE_FORMAT_VERSION,
        "speaker": MELO_SPEAKER if accent_mode == ACCENT_MELO_INDIA else KOREAN_REFERENCE,
        "text": text,
    }
    wire = json.dumps(identity, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(wire.encode("utf-8")).hexdigest()


class PersistentMeloIndiaRenderer:
    """Serialized client for one asynchronously warmed Melo/EN_INDIA worker."""

    def __init__(self, *, startup_timeout: float = MELO_STARTUP_TIMEOUT_SECONDS,
                 render_timeout: float = MELO_RENDER_TIMEOUT_SECONDS) -> None:
        self._startup_timeout = startup_timeout
        self._render_timeout = render_timeout
        self._lock = threading.Lock()
        self._ready = threading.Event()
        self._startup_failure: BaseException | None = None
        self._temporary = tempfile.TemporaryDirectory(prefix="voiceprobe-melo-worker-")
        self._process: subprocess.Popen[str] | None = None
        self._start()

    def _start(self) -> None:
        python = Path(os.environ.get("VOICEPROBE_ACCENT_PYTHON", str(DEFAULT_MELO_PYTHON)))
        if not python.is_file():
            raise RuntimeError(f"Melo environment is missing: {python}")
        environment = os.environ.copy()
        environment.update({"NUMBA_CACHE_DIR": str(Path(self._temporary.name) / "numba"),
                            "HF_HUB_OFFLINE": "1", "TRANSFORMERS_OFFLINE": "1"})
        self._process = subprocess.Popen(
            [str(python), str(MELO_CACHE_BUILDER), "--persistent-worker"],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, bufsize=1, env=environment,
        )
        threading.Thread(
            target=self._await_startup,
            name="voiceprobe-melo-india-startup",
            daemon=True,
        ).start()

    def _await_startup(self) -> None:
        try:
            message = self._read_message(self._startup_timeout, operation="startup")
            if message.get("event") != "ready" or message.get("speaker") != MELO_SPEAKER:
                raise RuntimeError(f"Unexpected Melo worker startup response: {message}")
        except BaseException as error:
            self._startup_failure = error
        finally:
            self._ready.set()

    @property
    def ready(self) -> bool:
        return self._ready.is_set() and self._startup_failure is None

    @property
    def pid(self) -> int | None:
        process = self._process
        return process.pid if process is not None and process.poll() is None else None

    def wait_until_ready(self, timeout: float | None = None) -> None:
        wait_timeout = self._startup_timeout if timeout is None else timeout
        if not self._ready.wait(wait_timeout):
            raise TimeoutError(
                f"Melo EN_INDIA readiness exceeded measured cold-start bound "
                f"of {wait_timeout:.1f}s"
            )
        if self._startup_failure is not None:
            raise RuntimeError("Melo EN_INDIA worker failed to become ready") from self._startup_failure

    def _read_message(self, timeout: float, *, operation: str) -> dict[str, object]:
        process = self._process
        if process is None or process.stdout is None:
            raise RuntimeError("Melo worker is not running")
        ready, _, _ = select.select([process.stdout], [], [], timeout)
        if not ready:
            self.close()
            raise TimeoutError(f"Melo EN_INDIA {operation} exceeded {timeout:.1f}s")
        line = process.stdout.readline()
        if not line:
            code = process.poll()
            self.close()
            raise RuntimeError(f"Melo worker exited during {operation} (code={code})")
        return json.loads(line)

    def render(self, text: str) -> bytes:
        if not isinstance(text, str) or not text.strip():
            raise ValueError("Melo rendering requires non-empty text")
        with self._lock:
            # A miss waits only for the one worker that warmup already started.
            # Cache hits never enter this method.
            self.wait_until_ready()
            process = self._process
            if process is None or process.poll() is not None or process.stdin is None:
                raise RuntimeError("Persistent Melo worker is unavailable")
            request_id = uuid.uuid4().hex
            wav_path = Path(self._temporary.name) / f"{request_id}.wav"
            process.stdin.write(json.dumps({"id": request_id, "text": text.strip(),
                                            "wav_path": str(wav_path)}) + "\n")
            process.stdin.flush()
            message = self._read_message(self._render_timeout, operation="render")
            if message.get("id") != request_id:
                raise RuntimeError(f"Melo worker response id mismatch: {message}")
            if message.get("event") == "error":
                raise RuntimeError(f"Melo worker {message.get('error_type')}: {message.get('error')}")
            if message.get("event") != "rendered":
                raise RuntimeError(f"Unexpected Melo worker response: {message}")
            pcm = read_validated_pcm(wav_path)
            wav_path.unlink(missing_ok=True)
            return pcm

    def close(self) -> None:
        process, self._process = self._process, None
        if process is not None:
            if process.stdin is not None:
                process.stdin.close()
            try:
                process.wait(timeout=1)
            except subprocess.TimeoutExpired:
                process.terminate()
                try:
                    process.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()


_melo_renderer: PersistentMeloIndiaRenderer | None = None
_melo_renderer_lock = threading.Lock()


def warm_melo_india_renderer() -> PersistentMeloIndiaRenderer:
    global _melo_renderer
    with _melo_renderer_lock:
        if _melo_renderer is None:
            _melo_renderer = PersistentMeloIndiaRenderer()
    return _melo_renderer


def _close_melo_renderer() -> None:
    global _melo_renderer
    with _melo_renderer_lock:
        renderer, _melo_renderer = _melo_renderer, None
    if renderer is not None:
        renderer.close()


atexit.register(_close_melo_renderer)


def render_melo_india_pcm(text: str) -> bytes:
    """Render arbitrary text through the persistent warmed Melo worker."""

    if not isinstance(text, str) or not text.strip():
        raise ValueError("Melo rendering requires non-empty text")
    return warm_melo_india_renderer().render(text)


